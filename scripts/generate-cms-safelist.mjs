/**
 * Generate the Tailwind safelist for CMS-authored utility classes.
 *
 * Several components accept per-section class overrides (`overlayClassName`,
 * `titleClassName`, `className`). While those values lived in page-body.tsx
 * Tailwind saw them in the source and generated the CSS. Now they arrive from
 * WordPress at runtime, so Tailwind has no way to know they exist and the
 * utilities are never emitted — a hero scrim silently disappears.
 *
 * This fetches the classes the CMS is actually using and writes them to a file
 * that styles.css pulls in with @source, so Tailwind generates exactly the
 * utilities the content needs and nothing more.
 *
 * Runs automatically via the `prebuild` script. If the CMS is unreachable the
 * existing safelist is kept, so a build never fails on a transient outage.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const OUT = join(ROOT, "src/styles/cms-safelist.txt");

const BASE = (process.env.WP_API_URL ?? "https://gomowebb.com/wow-backend").replace(/\/$/, "");

/*
 * A one-shot build step, so it bypasses any host proxy cache explicitly. The
 * runtime client deliberately does not: Next.js caches by URL, and a changing
 * query string would defeat that.
 */
const bust = () => `_cb=${Date.now()}`;

/** Props whose value is a list of Tailwind utilities. */
const CLASS_PROP = /ClassName$|^className$/;

function collectClasses(node, found = new Set()) {
  if (Array.isArray(node)) {
    for (const item of node) collectClasses(item, found);
    return found;
  }

  if (!node || typeof node !== "object") return found;

  for (const [key, value] of Object.entries(node)) {
    if (typeof value === "string" && CLASS_PROP.test(key)) {
      for (const cls of value.split(/\s+/)) {
        if (cls) found.add(cls);
      }
    } else {
      collectClasses(value, found);
    }
  }

  return found;
}

async function main() {
  let pages;

  try {
    const index = await fetch(`${BASE}/wp-json/wow/v1/pages?${bust()}`, { signal: AbortSignal.timeout(30000) });
    if (!index.ok) throw new Error(`HTTP ${index.status}`);
    pages = (await index.json()).items ?? [];
  } catch (error) {
    console.warn(`[safelist] CMS unreachable (${error.message}); keeping the existing safelist.`);
    return;
  }

  const classes = new Set();

  for (const page of pages) {
    try {
      const response = await fetch(`${BASE}/wp-json/wow/v1/page/${page.slug || "home"}?${bust()}`, {
        signal: AbortSignal.timeout(30000),
      });
      if (!response.ok) continue;
      collectClasses((await response.json()).sections ?? [], classes);
    } catch {
      // One unreachable page should not abandon the whole safelist.
    }
  }

  // Site settings carry class overrides too (e.g. the guest contact photo focus).
  try {
    const response = await fetch(`${BASE}/wp-json/wow/v1/globals?${bust()}`, { signal: AbortSignal.timeout(30000) });
    if (response.ok) collectClasses(await response.json(), classes);
  } catch {
    // Globals are optional for the safelist.
  }

  if (classes.size === 0) {
    console.warn("[safelist] no classes found; keeping the existing safelist.");
    return;
  }

  const sorted = [...classes].sort();
  const body = [
    "/*",
    " * Generated by scripts/generate-cms-safelist.mjs — do not edit by hand.",
    " *",
    " * Tailwind utilities that arrive from WordPress at runtime. styles.css",
    " * pulls this in with @source so the CSS is generated at build time.",
    " */",
    "",
    ...sorted,
    "",
  ].join("\n");

  mkdirSync(dirname(OUT), { recursive: true });

  const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";

  if (previous === body) {
    console.log(`[safelist] unchanged (${sorted.length} classes)`);
    return;
  }

  writeFileSync(OUT, body);
  console.log(`[safelist] wrote ${sorted.length} classes to src/styles/cms-safelist.txt`);
}

await main();
